// Prompts of the quick overview ("экскурс"). Kept apart from the tutor's
// prompts: no questions, no lesson, just a dense map of the subject.

export type BriefKind = "topic" | "files" | "repo" | "url" | "changes" | "review";
export type BriefDepth = 1 | 5 | 15;

export const DEPTHS: BriefDepth[] = [1, 5, 15];

/** How much to say at each reading time. */
const SIZE: Record<BriefDepth, string> = {
  1: "Время чтения — около минуты: только самое главное. Тезисов 4–5, разделы «Как это работает» и «Пример» по 2–3 строки, «Словарь» не больше 4 терминов, остальные разделы можно опустить.",
  5: "Время чтения — около пяти минут. Тезисов 6–9, все разделы, пример на 5–12 строк.",
  15: "Время чтения — около пятнадцати минут. Тезисов 10–14; в «Как это работает» до 8 шагов; два коротких примера; «Ловушки» и «Словарь» полнее. Всё так же списками, без длинных абзацев.",
};

const STYLE = `Стиль:
- По-русски, в Markdown. Без вступлений, без «давайте разберёмся», без заголовка первого уровня и без заключения.
- Каждый тезис — один пункт списка в одну-две строки: **термин или мысль** — суть. Никакой воды, вводных слов и повторов.
- Каждый пункт должен быть самодостаточным: по клику ученик раскроет любой пункт подробнее, поэтому не пиши «как сказано выше».
- Формулы — в $...$ и $$...$$, код — в блоках \`\`\` с указанием языка.
- Схему (процесс, поток данных, связи частей) можно нарисовать блоком \`\`\`mermaid: flowchart LR/TD или sequenceDiagram, до 12 узлов, подписи по-русски в кавычках, например A[\"Запрос\"] --> B[\"Проверка\"]. Рисуй, только когда схема понятнее текста. В разделе «Как это работает» схема особенно уместна.
- Только проверенные факты. Если чего-то не видно в материале, так и скажи коротко, не выдумывай.`;

const TOPIC_SHAPE = `Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: что это и зачем.
## Главное
нумерованный список тезисов.
## Как это работает
шаги или маленькая схема в блоке кода.
## Пример
минимальный пример кода или задача с решением.
## Ловушки
частые ошибки и заблуждения, по пункту на каждую.
## Словарь
термин — определение в одну строку.
## Куда дальше
3–5 тем, которые логично изучать следом, от простого к сложному.`;

const FILES_SHAPE = `Это экскурс по файлам, которые прислал ученик. Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: что делают эти файлы вместе.
## Главное
нумерованный список тезисов о том, как устроен код: ключевые функции, классы, данные, решения. Упоминай имена и \`файл:строка\`, где это помогает.
## Как это работает
путь выполнения или данных по шагам.
## Важные места
\`файл\` или \`файл → функция\` — за что отвечает, по пункту на каждое.
## Ловушки
неочевидное поведение, хрупкие места и возможные ошибки в этом коде.
## Словарь
термины и сокращения из кода — определение в одну строку.
## Куда дальше
что прочитать или попробовать следом, чтобы понять глубже.`;

const REPO_SHAPE = `Это экскурс по проекту (репозиторию) ученика. Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: что это за проект и для кого.
## Главное
нумерованный список тезисов об архитектуре: стек, ключевые решения, как части связаны.
## Как запустить
команды и что нужно заранее, если это видно из файлов.
## Карта проекта
таблица Markdown «Папка или файл | За что отвечает», 6–14 строк.
## Как это работает
путь основного запроса или данных по шагам, со ссылками на файлы.
## Ключевые файлы
\`путь\` — почему его стоит прочитать первым, 5–10 пунктов.
## Где что менять
«хочу X → смотри \`путь\`», 4–8 пунктов.
## Ловушки
неочевидные места, соглашения и подводные камни проекта.`;

const DOC_SHAPE = `Это экскурс по документу (статья, страница, PDF, конспект), который прислал ученик. Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: о чём документ и зачем его читать.
## Главное
нумерованный список ключевых мыслей документа в порядке важности.
## Как это работает
механизм, рассуждение или процесс из документа по шагам.
## Пример
пример из документа или свой минимальный, если в документе нет.
## Ловушки
ограничения, спорные места и частые неверные прочтения.
## Словарь
термины документа — определение в одну строку.
## Куда дальше
что прочитать или попробовать следом. Где помогает, ссылайся на разделы или страницы документа.`;

const CHANGES_SHAPE = `Это экскурс по изменениям в проекте ученика: история коммитов и изменения кода с прошлого раза. Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: что в целом поменялось.
## Главное
нумерованный список изменений по смыслу (новые возможности, исправления, переделки), со ссылками на файлы. Группируй мелкие правки.
## По коммитам
\`хеш\` — что сделано, по пункту на коммит или на группу мелких.
## Что затронуто
\`файл или модуль\` — что в нём изменилось.
## На что обратить внимание
ломающие изменения, миграции, новые зависимости и настройки, рискованные места, что стоит проверить руками.`;

const GROUNDED = `Ученик приложил свои материалы (лекции, учебник, заметки). Строй экскурс по ним: их содержание, термины, обозначения и примеры. Если для понимания нужно то, чего в материалах нет, добавь коротко и пометь «(не из материалов)».`;

const REVIEW_SHAPE = `Это разбор кода ученика, как у внимательного наставника: честно, по делу, с объяснением «почему». Код дан с номерами строк. Структура (заголовки второго уровня именно такие):
## Суть
одно предложение: что делает код и в каком он состоянии в целом.
## Что хорошо
нумерованный список удачных решений — коротко, чтобы ученик знал, что сохранить.
## Ошибки и риски
нумерованный список от самого важного: баги, неверные крайние случаи, проблемы безопасности и производительности, хрупкие места. Каждый пункт со ссылкой \`файл:строка\` и тем, к чему это приведёт.
## Как улучшить
конкретные правки: что поменять и почему, с короткими фрагментами «было → стало» в блоках кода. Сначала то, что исправляет ошибки, потом читаемость и стиль.
## Чему научиться
идеи и приёмы, которые стоит подтянуть, судя по этому коду, — по пункту, с объяснением в одну строку.`;

export function briefSystem(kind: BriefKind, depth: BriefDepth, doc = false, grounded = false, extra = ""): string {
  const shape =
    kind === "review" ? REVIEW_SHAPE : kind === "repo" ? REPO_SHAPE : kind === "changes" ? CHANGES_SHAPE : kind === "url" || (kind === "files" && doc) ? DOC_SHAPE : kind === "files" ? FILES_SHAPE : TOPIC_SHAPE;
  return `Ты составляешь краткий экскурс: сжатую, но полную карту предмета, которую ученик прочитает перед подробным изучением. Цель — максимум понимания на строку текста.

${shape}

${grounded ? `${GROUNDED}\n\n` : ""}${extra ? `${extra}\n\n` : ""}${SIZE[depth]}

${STYLE}`;
}

